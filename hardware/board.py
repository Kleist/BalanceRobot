#!/usr/bin/env python3
"""Check the board contract (`board.toml`) and generate the files that follow it.

    python3 hardware/board.py            # check, then write hardware/generated/
    python3 hardware/board.py --check    # check, and fail if generated/ is stale (CI)

Outputs, all in `hardware/generated/`:
- `board.scad`: the contract as OpenSCAD variables plus a few modules, for the
  chassis (`include <../hardware/generated/board.scad>`).
- `board.kicad_pcb`: a KiCad starter board with the outline, the mounting holes,
  the antenna keep-out and every contract part drawn on the fab layers, so the
  layout (F3) starts from exactly these positions.
- `board-front.svg`, `board-back.svg`: 1:1 drawings to print at 100 % and lay the
  real parts on (cells, USB plug, motor plugs) before anything is printed or ordered.

Only the Python standard library is used (Python 3.11+ for `tomllib`).
"""

from __future__ import annotations

import math
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "board.toml"
OUT = HERE / "generated"
HEADER = "Generated by hardware/board.py from hardware/board.toml. Do not edit."


@dataclass(frozen=True)
class Rect:
    """Axis-aligned rectangle, centre (x, y), size w x h."""

    x: float
    y: float
    w: float
    h: float

    @property
    def x0(self) -> float:
        return self.x - self.w / 2

    @property
    def x1(self) -> float:
        return self.x + self.w / 2

    @property
    def y0(self) -> float:
        return self.y - self.h / 2

    @property
    def y1(self) -> float:
        return self.y + self.h / 2

    def overlaps(self, other: Rect) -> bool:
        eps = 1e-9
        return (
            self.x0 < other.x1 - eps
            and other.x0 < self.x1 - eps
            and self.y0 < other.y1 - eps
            and other.y0 < self.y1 - eps
        )


def rect_of(item: dict) -> Rect:
    if "d" in item:  # a hole: its keep-out square is close enough for overlap checks
        size = item.get("keepout_d", item["d"])
        return Rect(item["x"], item["y"], size, size)
    return Rect(item["x"], item["y"], item["w"], item["h"])


def sides(item: dict) -> set[str]:
    side = item.get("side", "both")
    return {"front", "back"} if side == "both" else {side}


def check(c: dict) -> list[str]:
    """Return a list of problems; empty means the contract is consistent."""
    errors: list[str] = []
    b = c["board"]
    board = Rect(b["width"] / 2, b["height"] / 2, b["width"], b["height"])
    holes = c.get("hole", [])
    parts = c.get("part", [])
    keepouts = c.get("keepout", [])

    names = [i["name"] for i in holes + parts + keepouts]
    for n in sorted({n for n in names if names.count(n) > 1}):
        errors.append(f"duplicate name {n}")

    def inside(r: Rect) -> bool:
        eps = 1e-9
        return (
            r.x0 >= board.x0 - eps
            and r.x1 <= board.x1 + eps
            and r.y0 >= board.y0 - eps
            and r.y1 <= board.y1 + eps
        )

    for item in holes + parts + keepouts:
        if not inside(rect_of(item)):
            errors.append(f"{item['name']} is not inside the board outline")

    # Holes must keep their screw-head area free of the board corners' radius.
    r = b["corner_radius"]
    for h in holes:
        k = h["keepout_d"] / 2
        if min(h["x"], b["width"] - h["x"], h["y"], b["height"] - h["y"]) < k - 0.5:
            errors.append(f"{h['name']} keep-out runs off the board edge")
        if r > min(h["x"], h["y"], b["width"] - h["x"], b["height"] - h["y"]):
            errors.append(f"{h['name']} sits inside the rounded corner")

    # A part that points out of an edge must be flush with that edge.
    for p in parts:
        edge = p.get("edge")
        if edge is None:
            continue
        rp = rect_of(p)
        gap = {
            "left": rp.x0 - board.x0,
            "right": board.x1 - rp.x1,
            "bottom": rp.y0 - board.y0,
            "top": board.y1 - rp.y1,
        }.get(edge)
        if gap is None:
            errors.append(f"{p['name']}: unknown edge {edge!r}")
        elif abs(gap) > 0.01:
            errors.append(f"{p['name']} should be flush with the {edge} edge (gap {gap:.2f} mm)")
        if "opening" not in p:
            errors.append(f"{p['name']} points out of an edge but has no chassis opening")

    # Parts may not overlap other parts on the same side, nor hole keep-outs
    # (holes are clear on both sides).
    for i, p in enumerate(parts):
        for q in parts[i + 1 :]:
            if sides(p) & sides(q) and rect_of(p).overlaps(rect_of(q)):
                errors.append(f"{p['name']} overlaps {q['name']}")
        for h in holes:
            if rect_of(p).overlaps(rect_of(h)):
                errors.append(f"{p['name']} overlaps the keep-out of hole {h['name']}")

    # Keep-outs: nothing else on those sides, except the module that owns the antenna.
    for k in keepouts:
        for p in parts:
            if p["name"] == "esp32_module" and k["name"] == "antenna":
                continue
            if sides(p) & sides(k) and rect_of(p).overlaps(rect_of(k)):
                errors.append(f"{p['name']} is inside keep-out {k['name']}")

    # The antenna must be at the top edge, inside the module, and away from the cells.
    ant = next((k for k in keepouts if k["name"] == "antenna"), None)
    module = next((p for p in parts if p["name"] == "esp32_module"), None)
    if ant is None or module is None:
        errors.append("contract needs an esp32_module part and an antenna keep-out")
    else:
        ra, rm = rect_of(ant), rect_of(module)
        if abs(ra.y1 - board.y1) > 0.01 or abs(rm.y1 - board.y1) > 0.01:
            errors.append("module and antenna keep-out must reach the top edge")
        if ra.x0 < rm.x0 - 0.01 or ra.x1 > rm.x1 + 0.01 or ra.y0 < rm.y0 - 0.01:
            errors.append("antenna keep-out must lie within the module's outline")
        for p in parts:
            if p["name"].startswith("battery"):
                gap = ra.y0 - rect_of(p).y1
                if gap < 10.0:
                    errors.append(f"{p['name']} is only {gap:.1f} mm from the antenna (need 10)")

    # Every part fits under the clearance the chassis reserves for its side.
    for p in parts:
        limit = b[f"{p['side']}_clearance"]
        if p["height"] > limit:
            errors.append(f"{p['name']} is {p['height']} mm tall, more than {p['side']}_clearance {limit}")

    return errors


# ---------------------------------------------------------------- OpenSCAD


def fmt(v: float) -> str:
    return f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def scad(c: dict) -> str:
    b = c["board"]
    out = [f"// {HEADER}", "// Units mm, seen from the board's front (SMD side), origin bottom-left,", "// +x right, +y up, +z out of the front.", ""]
    for key in ("width", "height", "thickness", "corner_radius", "front_clearance", "back_clearance"):
        out.append(f"board_{key} = {fmt(float(b[key]))};")
    out.append("")
    out.append("// [name, x, y, d, keepout_d]")
    out.append("board_holes = [")
    out += [f'    ["{h["name"]}", {fmt(h["x"])}, {fmt(h["y"])}, {fmt(h["d"])}, {fmt(h["keepout_d"])}],' for h in c["hole"]]
    out.append("];")
    out.append("")
    out.append('// [name, side ("front"/"back"), x, y, w, h, height, edge ("" if none), opening_w, opening_h]')
    out.append("board_parts = [")
    for p in c["part"]:
        o = p.get("opening", {"w": 0, "h": 0})
        out.append(
            f'    ["{p["name"]}", "{p["side"]}", {fmt(p["x"])}, {fmt(p["y"])}, {fmt(p["w"])}, {fmt(p["h"])}, '
            f'{fmt(p["height"])}, "{p.get("edge", "")}", {fmt(float(o["w"]))}, {fmt(float(o["h"]))}],'
        )
    out.append("];")
    out.append("")
    out.append("// [name, side, x, y, w, h]")
    out.append("board_keepouts = [")
    out += [
        f'    ["{k["name"]}", "{k["side"]}", {fmt(k["x"])}, {fmt(k["y"])}, {fmt(k["w"])}, {fmt(k["h"])}],'
        for k in c["keepout"]
    ]
    out.append("];")
    out.append(
        """
function board_part(name) = board_parts[search([name], board_parts)[0]];

// The board outline as a 2D shape.
module board_outline() {
    r = board_corner_radius;
    translate([r, r]) offset(r = r) square([board_width - 2 * r, board_height - 2 * r]);
}

// The bare board with its holes, front face at z = 0 (the board itself is z -thickness..0).
module board_pcb() {
    translate([0, 0, -board_thickness]) linear_extrude(board_thickness) difference() {
        board_outline();
        for (h = board_holes) translate([h[1], h[2]]) circle(d = h[3], $fn = 32);
    }
}

// A stand-in for the assembled board: the PCB plus a box for every contract part.
// Good enough to check fits in the chassis; not a model of the real parts.
module board_dummy() {
    color("green") board_pcb();
    for (p = board_parts) {
        z0 = p[1] == "front" ? 0 : -board_thickness - p[6];
        color(p[1] == "front" ? "silver" : "steelblue")
            translate([p[2] - p[4] / 2, p[3] - p[5] / 2, z0]) cube([p[4], p[5], p[6]]);
    }
}

// The free space the board needs: board outline extruded by both clearances.
// Subtract it from the body to get the board's pocket.
module board_envelope() {
    translate([0, 0, -board_thickness - board_back_clearance])
        linear_extrude(board_thickness + board_back_clearance + board_front_clearance) board_outline();
}

// Wall cut-outs for parts that point out of an edge, `depth` deep from the board edge.
// The opening is centred on the part, across the board plane on its z centre.
module board_edge_openings(depth = 10) {
    for (p = board_parts) if (p[7] != "") {
        zc = p[1] == "front" ? p[6] / 2 : -board_thickness - p[6] / 2;
        ow = p[8];
        oh = p[9];
        if (p[7] == "left") translate([-depth, p[3] - ow / 2, zc - oh / 2]) cube([depth, ow, oh]);
        if (p[7] == "right") translate([board_width, p[3] - ow / 2, zc - oh / 2]) cube([depth, ow, oh]);
        if (p[7] == "bottom") translate([p[2] - ow / 2, -depth, zc - oh / 2]) cube([ow, depth, oh]);
        if (p[7] == "top") translate([p[2] - ow / 2, board_height, zc - oh / 2]) cube([ow, depth, oh]);
    }
}
"""
    )
    return "\n".join(out)


